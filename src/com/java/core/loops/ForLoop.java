package com.java.core.loops;

public class ForLoop {

	public static void main(String[] args) {

		System.out.println("START");
		for(int i = 1; i<=10; i++) {
			System.out.println("hii "+i);
		}
		System.out.println("END");
		
		for(int i = 5; i > 0; i--) {
			System.out.println(i);
		}
		
		for(int i =0;  i >= 0; i++) {
			System.out.println("infinite");
		}
	}

}
