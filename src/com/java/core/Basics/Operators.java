package com.java.core.Basics;

public class Operators {

	public static void main(String[] args) {

		int a = 10;
		int b = 5;
		
		// add, subtract, multiply, division and modulus
	
		int sum = a+b;
		System.out.println("Sum is "+sum);
		
		int subs = a-b;
		System.out.println("Difference is "+subs);
		
		int mul = a*b;
		System.out.println("Product is "+mul);
		
		int div = a/b;
		System.out.println("Quotient after division is "+div);

		int mod = a%b;
		System.out.println("Remainder after division is"+mod);
	}

}
